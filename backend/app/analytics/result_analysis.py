"""
Converts a raw SQL result into a structured statistical summary
using Pandas.

This is the layer that turns "rows of data" into "facts about the
data" — column types, ranges, nulls, distinct counts. Visualization
(Phase 11) and explanation (Phase 12) both consume this output
instead of re-deriving statistics themselves, which keeps the
numbers a user sees consistent and correct across the whole response.
"""

from typing import Any

import pandas as pd
from pydantic import BaseModel


class ColumnSummary(BaseModel):
    name: str
    inferred_type: str  # "numeric" | "datetime" | "categorical" | "text"
    null_count: int
    # numeric-only
    min_value: float | None = None
    max_value: float | None = None
    mean_value: float | None = None
    sum_value: float | None = None
    # datetime-only
    min_date: str | None = None
    max_date: str | None = None
    # categorical/text-only
    distinct_count: int | None = None
    top_value: str | None = None


class ResultAnalysis(BaseModel):
    row_count: int
    column_summaries: list[ColumnSummary]
    notes: list[str]


MAX_ABSOLUTE_DISTINCT_FOR_CATEGORICAL = 20


def _infer_column_type(series: pd.Series) -> str:
    """
    Classifies a column as numeric, datetime, categorical, or text.

    Categorical detection uses TWO signals, not just a ratio: a low
    absolute distinct count (<=20) OR a low distinct-to-row ratio
    (<0.5). The absolute check matters because ratio alone breaks
    down on small result sets — e.g. 5 distinct statuses across
    exactly 5 rows gives ratio 1.0 (looks like "all unique"), even
    though order status is unambiguously a category with a small,
    fixed set of real-world values. The absolute cap catches this;
    the ratio catches the opposite failure mode (e.g. a column with
    200 distinct values out of 10,000 rows — low ratio, but too many
    distinct values to sensibly treat as a small category set).
    """
    if pd.api.types.is_numeric_dtype(series):
        return "numeric"
    if pd.api.types.is_datetime64_any_dtype(series):
        return "datetime"

    non_null = series.dropna()
    if len(non_null) == 0:
        return "text"

    distinct_count = non_null.nunique()
    distinct_ratio = distinct_count / len(non_null)

    if distinct_count <= MAX_ABSOLUTE_DISTINCT_FOR_CATEGORICAL or distinct_ratio < 0.5:
        return "categorical"
    return "text"


def _summarize_column(name: str, series: pd.Series) -> ColumnSummary:
    inferred_type = _infer_column_type(series)
    null_count = int(series.isna().sum())

    if inferred_type == "numeric":
        return ColumnSummary(
            name=name,
            inferred_type=inferred_type,
            null_count=null_count,
            min_value=float(series.min()) if series.notna().any() else None,
            max_value=float(series.max()) if series.notna().any() else None,
            mean_value=float(series.mean()) if series.notna().any() else None,
            sum_value=float(series.sum()) if series.notna().any() else None,
        )

    if inferred_type == "datetime":
        return ColumnSummary(
            name=name,
            inferred_type=inferred_type,
            null_count=null_count,
            min_date=str(series.min()) if series.notna().any() else None,
            max_date=str(series.max()) if series.notna().any() else None,
        )

    # categorical or text
    non_null = series.dropna()
    top_value = str(non_null.mode().iloc[0]) if not non_null.empty and not non_null.mode().empty else None
    return ColumnSummary(
        name=name,
        inferred_type=inferred_type,
        null_count=null_count,
        distinct_count=int(non_null.nunique()),
        top_value=top_value,
    )


def _build_notes(row_count: int, summaries: list[ColumnSummary]) -> list[str]:
    """
    Human-readable, factual observations derived directly from the
    computed summaries — not generated by an LLM. These are exactly
    the kind of "caveats" Phase 12's explanation will want to surface,
    pre-verified rather than something the model has to notice itself.
    """
    notes: list[str] = []

    if row_count == 0:
        notes.append("The query returned no rows.")
        return notes

    columns_with_nulls = [s.name for s in summaries if s.null_count > 0]
    if columns_with_nulls:
        notes.append(f"Missing values found in: {', '.join(columns_with_nulls)}.")
    else:
        notes.append("No missing values in any column.")

    if row_count == 1:
        notes.append("Result is a single value/row — likely a direct aggregate answer.")

    return notes


def analyze_result(columns: list[str], rows: list[dict[str, Any]]) -> ResultAnalysis:
    if not rows:
        return ResultAnalysis(row_count=0, column_summaries=[], notes=["The query returned no rows."])

    df = pd.DataFrame(rows, columns=columns)

    # Coerce Decimal/numeric-as-object columns (e.g. Postgres NUMERIC)
    # to real numeric dtypes before classification.
    for col in columns:
        df[col] = _try_coerce_numeric(df[col])

    summaries = [_summarize_column(col, df[col]) for col in columns]
    notes = _build_notes(len(df), summaries)

    return ResultAnalysis(row_count=len(df), column_summaries=summaries, notes=notes)
def _try_coerce_numeric(series: pd.Series) -> pd.Series:
    """
    Postgres NUMERIC/DECIMAL columns come back from psycopg2/SQLAlchemy
    as Python Decimal objects, not float — so Pandas sees dtype
    'object' and is_numeric_dtype() returns False, even though the
    values are genuinely numeric. We attempt a numeric conversion on
    any object-dtype column; if it succeeds, the column behaves
    correctly as numeric for all downstream classification and stats.
    If conversion fails (it's genuinely text), we leave it untouched.
    """
    if series.dtype == object:
        try:
            return pd.to_numeric(series)
        except (ValueError, TypeError):
            return series
    return series